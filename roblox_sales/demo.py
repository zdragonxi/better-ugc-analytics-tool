"""A SYNTHETIC demo database: invented stores, items, buyers and numbers.

Used for screenshots, tests and trying the dashboard without a cookie. Nothing in it comes
from a real account; group ids are deliberately fake round numbers.
"""
from __future__ import annotations

import json
import math
import os
import random
import time
from datetime import datetime, timedelta, timezone

from . import store

GROUPS = [(1111111, "Demo Studio"), (2222222, "Pixel Forge")]
SEPARATE = (3333333, "Collab Store")       # a store kept out of the combined totals
ITEMS = ["Neon Visor", "Frost Wings", "Pixel Crown", "Starlight Halo", "Mossy Backpack",
         "Chrome Shades", "Ember Horns", "Cloud Scarf", "Glitch Mask", "Velvet Bow",
         "Comet Tail", "Lunar Earrings", "Sunny Bucket Hat", "Koi Pond Pin"]
DAYS = 150


def write_config(path: str, db_path: str, port: int = 8930) -> None:
    lines = ["# SYNTHETIC demo configuration — generated by `python -m roblox_sales demo`",
             "[app]", "host = 127.0.0.1", f"port = {port}", f"db_path = {db_path}",
             "user_store_name = My account", ""]
    for gid, name in GROUPS + [SEPARATE]:
        lines += [f"[group:{gid}]", f"name = {name}"]
        if gid == SEPARATE[0]:
            lines.append("combine = false")
        lines.append("")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))


def build(path: str, seed: int = 7, now: datetime | None = None) -> None:
    rnd = random.Random(seed)
    now = now or datetime.now(timezone.utc)
    if os.path.exists(path):
        os.remove(path)
    for ext in ("-wal", "-shm"):
        if os.path.exists(path + ext):
            os.remove(path + ext)
    db = store.connect(path)
    stores = [(f"group:{g}", n) for g, n in GROUPS] + [(f"group:{SEPARATE[0]}", SEPARATE[1]),
                                                       ("user", "My account")]
    # each store sells a subset of items at fixed prices; creator cut is 30 % of price
    catalogue = {}
    for i, (src, _) in enumerate(stores):
        names = rnd.sample(ITEMS, 6 if src != "user" else 3)
        catalogue[src] = [(1_000_000 + i * 100 + j, nm, rnd.choice([25, 40, 55, 75, 99, 120]),
                           rnd.uniform(0.4, 1.6)) for j, nm in enumerate(names)]
    scale = {"group:1111111": 55, "group:2222222": 30, f"group:{SEPARATE[0]}": 9, "user": 3}
    start = (now - timedelta(days=DAYS)).replace(hour=0, minute=0, second=0, microsecond=0)
    cutoff_csv = now.replace(day=1, hour=0, minute=0, second=0, microsecond=0)  # this month = API
    rows = []
    n = 0
    for d in range(DAYS + 1):
        day = start + timedelta(days=d)
        trend = 0.55 + 0.9 * d / DAYS                       # a store that grows
        weekly = 1.0 + 0.25 * math.sin(2 * math.pi * (day.weekday() - 2) / 7)
        spike = 2.4 if d in (DAYS - 41, DAYS - 12) else 1.0  # two launch days
        for src, _ in stores:
            for aid, name, price, pop in catalogue[src]:
                lam = scale[src] / 6 * trend * weekly * spike * pop
                k = max(0, int(rnd.gauss(lam, math.sqrt(lam + 1))))
                for _ in range(k):
                    t = day + timedelta(seconds=rnd.randint(0, 86399))
                    if t >= now:
                        continue
                    n += 1
                    rent = rnd.random() < 0.03                # occasional rental payment
                    robux = max(1, int(price * 0.3 * (0.1 if rent else 1)))
                    from_csv = t < cutoff_csv
                    rows.append((f"demo-{n:07d}", src, store.canon(t), aid, name,
                                 9_000_000 + rnd.randint(0, 400_000), robux,
                                 1 if now - t < timedelta(days=30) else 0,
                                 (("Game" if rnd.random() < 0.78 else "Website") if from_csv else None),
                                 "csv" if from_csv else "api"))
    rows.sort(key=lambda r: r[2])
    db.executemany("INSERT INTO sales (id, source, created, asset_id, asset_name, buyer_id, robux, "
                   "is_pending, location, origin) VALUES (?,?,?,?,?,?,?,?,?,?)", rows)
    # imported-months log for the finished months
    months = sorted({r[2][:7] for r in rows if r[9] == "csv"})
    for src, _ in stores:
        if src == "user":
            continue
        for m in months:
            cnt = db.execute("SELECT COUNT(*) FROM sales WHERE source=? AND created LIKE ?",
                             (src, m + "%")).fetchone()[0]
            db.execute("INSERT INTO csv_imports VALUES (?,?,?,?,?,?)",
                       (src, m, f"Sales_Group{src.split(':')[1]}_{m}.csv", cnt, 0, int(time.time())))
    # financial snapshot (what the poller would have fetched)
    fin = {}
    for src, _ in stores:
        if src == "user":
            continue
        last30 = db.execute("SELECT COALESCE(SUM(robux),0) FROM sales WHERE source=? AND is_pending=1",
                            (src,)).fetchone()[0]
        fin[src] = {"funds": int(last30 * rnd.uniform(1.8, 3.5)), "pending": int(last30),
                    "sales_month": int(last30 * 0.4), "updated": int(time.time())}
    store.set_meta(db, "financials", json.dumps(fin), commit=False)
    # items-on-sale counts (what a complete by-creator walk would have stored)
    t = int(time.time())
    cat = {f"group:{gid}": {"items": n, "as_of": t - age, "attempt": t - age, "error": None,
                            "types": {"8": n}}
           for gid, n, age in ((GROUPS[0][0], 412, 240), (GROUPS[1][0], 236, 300),
                               (SEPARATE[0], 58, 3 * 3600))}
    store.set_meta(db, "catalog", json.dumps(cat), commit=False)
    # the current balance shown in the top-bar pill
    store.set_meta(db, "balance", json.dumps({"robux": 214_793, "ts": int(time.time()) - 60}),
                   commit=False)
    for src, _ in stores:
        store.set_watermark(db, src, now - timedelta(minutes=40))
    store.bump_epoch(db, commit=False)
    db.commit()
    db.close()
